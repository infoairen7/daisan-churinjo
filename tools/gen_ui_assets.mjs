// Embed the pack's UI parts (SVG/PNG) as data: URIs so the page never depends on extra image requests.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = 'public/assets/ui';
const out = {};
for (const f of readdirSync(dir).sort()) {
  const m = /^(.*)\.(svg|png)$/.exec(f); if (!m) continue;
  const mime = m[2] === 'svg' ? 'image/svg+xml' : 'image/png';
  out[m[1]] = `data:${mime};base64,` + readFileSync(`${dir}/${f}`).toString('base64');
}
writeFileSync('src/game/ui_assets.gen.ts', '// generated by tools/gen_ui_assets.mjs — do not edit\nexport const UI: Record<string, string> = ' + JSON.stringify(out, null, 0) + ';\n');
console.log('embedded', Object.keys(out).length, 'ui parts');
